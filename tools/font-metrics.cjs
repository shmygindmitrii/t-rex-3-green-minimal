// Regenerate watchface/font-metrics.js from the TTF files in assets/<target>/fonts.
// Run after adding or replacing a font: node tools/font-metrics.cjs
const fs = require('node:fs')
const path = require('node:path')

const ROOT = path.join(__dirname, '..')
const ASSETS = path.join(ROOT, 'assets/480x480-amazfit-t-rex-3')
const OUT = path.join(ROOT, 'watchface/font-metrics.js')
// Characters measured for every font: everything a watch face is likely to print.
const CHARS = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join('')

function readFont(file) {
  const buf = fs.readFileSync(file)
  const tables = {}
  for (let i = 0, n = buf.readUInt16BE(4); i < n; i++) {
    const rec = 12 + i * 16
    tables[buf.toString('latin1', rec, rec + 4)] = buf.readUInt32BE(rec + 8)
  }
  const unitsPerEm = buf.readUInt16BE(tables.head + 18)
  const numHMetrics = buf.readUInt16BE(tables.hhea + 34)
  const advance = (glyph) => buf.readUInt16BE(tables.hmtx + 4 * Math.min(glyph, numHMetrics - 1))
  // cmap format 4 (BMP) lookup.
  let sub = null
  for (let i = 0, n = buf.readUInt16BE(tables.cmap + 2); i < n; i++) {
    const rec = tables.cmap + 4 + i * 8
    const off = tables.cmap + buf.readUInt32BE(rec + 4)
    if (buf.readUInt16BE(off) === 4) { sub = off; break }
  }
  if (sub === null) throw new Error(file + ': no cmap format 4 table')
  const segX2 = buf.readUInt16BE(sub + 6)
  const ends = sub + 14, starts = ends + segX2 + 2, deltas = starts + segX2, ranges = deltas + segX2
  const glyphOf = (code) => {
    for (let s = 0; s < segX2; s += 2) {
      if (code > buf.readUInt16BE(ends + s)) continue
      const start = buf.readUInt16BE(starts + s)
      if (code < start) return 0
      const delta = buf.readInt16BE(deltas + s)
      const ro = buf.readUInt16BE(ranges + s)
      if (ro === 0) return (code + delta) & 0xffff
      const g = buf.readUInt16BE(ranges + s + ro + 2 * (code - start))
      return g === 0 ? 0 : (g + delta) & 0xffff
    }
    return 0
  }
  const widths = {}
  for (const ch of CHARS) {
    const g = glyphOf(ch.charCodeAt(0))
    if (g !== 0 || ch === ' ') widths[ch] = +(advance(g) / unitsPerEm).toFixed(4)
  }
  return { fallback: +(advance(glyphOf('0'.charCodeAt(0)) || 0) / unitsPerEm).toFixed(4), widths }
}

const fonts = {}
const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full)
    else if (/\.(ttf|otf)$/i.test(entry.name)) fonts[path.relative(ASSETS, full).split(path.sep).join('/')] = readFont(full)
  }
}
walk(path.join(ASSETS, 'fonts'))

const body = Object.entries(fonts).map(([file, m]) =>
  `  '${file}': {\n    fallback: ${m.fallback},\n    widths: ${JSON.stringify(m.widths)},\n  },`).join('\n')
fs.writeFileSync(OUT, `// GENERATED by tools/font-metrics.cjs — do not edit by hand.
// Advance width of each character as a fraction of the font size.
export const FONT_METRICS = {
${body}
}
`)
console.log('Wrote ' + path.relative(ROOT, OUT) + ' for ' + Object.keys(fonts).length + ' fonts')
